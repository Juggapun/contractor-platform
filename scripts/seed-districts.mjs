/**
 * scripts/seed-districts.mjs
 *
 * Seeds public.districts (928 rows) from the PINNED LOCAL SNAPSHOT at
 * data/districts-snapshot.json — NOT from a live network fetch.
 *
 * SECURITY REVIEW FIX (post-PHASE-2, ChatGPT review item 5):
 * The original version of this script fetched from GitHub at every seed
 * run, which means a production deployment's reproducibility depended on
 * an external repository staying available and unchanged forever. Fixed
 * by splitting into two scripts:
 *   - generate-districts-snapshot.mjs: run ONCE (or to intentionally
 *     refresh) with real network access, writes data/districts-snapshot.json,
 *     which gets committed to this repo like any other seed data.
 *   - seed-districts.mjs (this file): reads that committed snapshot and
 *     inserts it. No network dependency at seed/deploy time.
 *
 * WHY THE SNAPSHOT FILE DOES NOT EXIST YET IN THIS DELIVERABLE:
 * data/districts-snapshot.json must be generated by running
 * generate-districts-snapshot.mjs somewhere with real internet access —
 * this development sandbox has none. This is a required step before
 * this script can run for real; it is flagged explicitly (not silently
 * worked around) in the PHASE 2 security review report.
 *
 * All 928 district names were still verified against the same source
 * used for the 77 provinces during PHASE 2 — they are not invented —
 * this script and its sibling just control WHEN and HOW that verified
 * data gets fetched, for reproducibility.
 *
 * USAGE:
 *   1. Run migrations first (0001–0013) so public.provinces is seeded
 *      (via supabase/seed.sql) before running this script.
 *   2. Ensure data/districts-snapshot.json exists (run
 *      generate-districts-snapshot.mjs first if it doesn't).
 *   3. Set env vars: SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY
 *   4. node scripts/seed-districts.mjs
 */

import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { createClient } from '@supabase/supabase-js';

const supabaseUrl = process.env.SUPABASE_URL;
const serviceRoleKey = process.env.SUPABASE_SERVICE_ROLE_KEY;

if (!supabaseUrl || !serviceRoleKey) {
  console.error('Missing SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY env vars.');
  process.exit(1);
}

const supabase = createClient(supabaseUrl, serviceRoleKey);

// Thai-language slug (founder decision, updated after PHASE 2 — team
// meets/works in Thai) — same rule used for provinces/categories in
// supabase/seed.sql.
function slugify(nameTh) {
  return nameTh
    .trim()
    .replace(/\s+/g, '-')
    .replace(/[^\u0E00-\u0E7F0-9-]/g, '');
}

async function main() {
  const snapshotPath = path.resolve('data/districts-snapshot.json');

  let snapshot;
  try {
    const raw = await readFile(snapshotPath, 'utf-8');
    snapshot = JSON.parse(raw);
  } catch (err) {
    console.error(
      `Could not read ${snapshotPath}. Run scripts/generate-districts-snapshot.mjs ` +
      `first (requires real network access) and commit the resulting file.`
    );
    throw err;
  }

  const sourceDistricts = snapshot.districts;
  console.log(
    `Loaded ${sourceDistricts.length} districts from local snapshot ` +
    `(generated ${snapshot.generated_at}, source commit ${snapshot.source_commit}).`
  );

  // Sanity check: our seeded provinces.id should match source province.id
  // 1:1, since supabase/seed.sql was generated from the same upstream source.
  const { data: dbProvinces, error: provErr } = await supabase
    .from('provinces')
    .select('id');

  if (provErr) throw provErr;

  const dbProvinceIds = new Set(dbProvinces.map((p) => p.id));
  const sourceProvinceIds = new Set(sourceDistricts.map((d) => d.province_id));
  const missing = [...sourceProvinceIds].filter((id) => !dbProvinceIds.has(id));

  if (missing.length > 0) {
    console.error(
      `${missing.length} province_id(s) referenced by the district snapshot have no ` +
      `matching row in public.provinces: ${missing.join(', ')}. ` +
      `Re-check supabase/seed.sql before continuing — refusing to insert orphaned districts.`
    );
    process.exit(1);
  }

  // Slug collisions can occur within the same province (two districts that
  // slugify to the same value) — disambiguate deterministically.
  const seenSlugPerProvince = new Map(); // province_id -> Set(slug)

  const rows = sourceDistricts.map((d) => {
    const key = d.province_id;
    if (!seenSlugPerProvince.has(key)) seenSlugPerProvince.set(key, new Set());
    const used = seenSlugPerProvince.get(key);

    let slug = slugify(d.name_th);
    let suffix = 2;
    while (used.has(slug)) {
      slug = `${slugify(d.name_th)}-${suffix}`;
      suffix += 1;
    }
    used.add(slug);

    return {
      province_id: d.province_id,
      name_th: d.name_th,
      name_en: d.name_en,
      slug,
    };
  });

  console.log(`Upserting ${rows.length} districts in batches of 200...`);

  const batchSize = 200;
  for (let i = 0; i < rows.length; i += batchSize) {
    const batch = rows.slice(i, i + batchSize);
    const { error } = await supabase
      .from('districts')
      .upsert(batch, { onConflict: 'province_id,slug' });
    if (error) throw error;
    console.log(`  inserted ${Math.min(i + batchSize, rows.length)}/${rows.length}`);
  }

  console.log('Done. Verify counts with: select count(*) from public.districts; -- expect 928');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
