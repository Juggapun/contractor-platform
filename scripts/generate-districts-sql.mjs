/**
 * scripts/generate-districts-sql.mjs
 *
 * Regenerates supabase/seed_districts.sql from the already-committed,
 * already-verified data/districts-snapshot.json — same source and same
 * per-province slug logic as scripts/seed-districts.mjs, just emitted as
 * plain SQL instead of executed over the Supabase JS client.
 *
 * WHY THIS EXISTS (Issue #12 follow-up):
 * seed-districts.mjs requires live network access to a Supabase project
 * (SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY, @supabase/supabase-js). A
 * real Beta deployment's owner can run SQL through the Supabase dashboard's
 * SQL Editor (as documented in docs/DEPLOYMENT.md for the schema
 * migrations and supabase/seed.sql already), but running an arbitrary
 * Node script requires a machine with the Supabase JS client, env vars,
 * and outbound network access configured — a heavier ask. This script
 * produces the same 930 rows as a static .sql file so the owner can run
 * it the exact same way as everything else in supabase/, no Node
 * environment or extra credentials required beyond what SQL Editor access
 * already implies.
 *
 * USAGE (run once, or to regenerate after data/districts-snapshot.json
 * is refreshed via generate-districts-snapshot.mjs):
 *   node scripts/generate-districts-sql.mjs
 *
 * Writes supabase/seed_districts.sql, which should be committed like any
 * other generated seed file.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

function slugify(nameTh) {
  return nameTh
    .trim()
    .replace(/\s+/g, '-')
    .replace(/[^฀-๿0-9-]/g, '');
}

function sqlString(s) {
  return `'${s.replace(/'/g, "''")}'`;
}

async function main() {
  const snapshotPath = path.resolve('data/districts-snapshot.json');
  const raw = await readFile(snapshotPath, 'utf-8');
  const snapshot = JSON.parse(raw);
  const sourceDistricts = snapshot.districts;

  // Same disambiguation logic as scripts/seed-districts.mjs: slugs only
  // need to be unique within a province (see the `unique (province_id,
  // slug)` constraint in supabase/migrations/0002_geography.sql).
  const seenSlugPerProvince = new Map();
  const rows = sourceDistricts.map((d) => {
    const key = d.province_id;
    if (!seenSlugPerProvince.has(key)) seenSlugPerProvince.set(key, new Set());
    const used = seenSlugPerProvince.get(key);

    let slug = slugify(d.name_th);
    let suffix = 2;
    while (used.has(slug)) {
      slug = `${slugify(d.name_th)}-${suffix}`;
      suffix += 1;
    }
    used.add(slug);

    return { province_id: d.province_id, name_th: d.name_th, name_en: d.name_en, slug };
  });

  const lines = [];
  lines.push('-- supabase/seed_districts.sql');
  lines.push('-- ============================================================');
  lines.push('-- public.districts reference data (Amphoe/Khet, ~930 rows)');
  lines.push('-- ============================================================');
  lines.push('-- AUTO-GENERATED by scripts/generate-districts-sql.mjs from');
  lines.push('-- data/districts-snapshot.json. Do not hand-edit this file --');
  lines.push('-- regenerate it instead if the snapshot ever changes.');
  lines.push('--');
  lines.push('-- Source: https://github.com/kongvut/thai-province-data (MIT),');
  lines.push(`-- commit ${snapshot.source_commit} -- the same upstream source`);
  lines.push("-- already used for this project's provinces and categories in");
  lines.push('-- supabase/seed.sql. Real Thai administrative-division reference');
  lines.push('-- data, not invented, not test/placeholder data.');
  lines.push('--');
  lines.push('-- Run this AFTER supabase/seed.sql (provinces must exist first --');
  lines.push('-- province_id below is a foreign key into public.provinces).');
  lines.push('-- Safe to re-run: `on conflict do nothing` makes it idempotent.');
  lines.push('--');
  lines.push(`-- Rows: ${rows.length}`);
  lines.push('');
  lines.push('insert into public.districts (province_id, name_th, name_en, slug)');
  lines.push('values');
  const valueLines = rows.map((r, i) => {
    const comma = i === rows.length - 1 ? '' : ',';
    return `  (${r.province_id}, ${sqlString(r.name_th)}, ${sqlString(r.name_en)}, ${sqlString(r.slug)})${comma}`;
  });
  lines.push(...valueLines);
  lines.push('on conflict (province_id, slug) do nothing;');
  lines.push('');

  const outPath = path.resolve('supabase/seed_districts.sql');
  await writeFile(outPath, lines.join('\n'));
  console.log(`Wrote ${rows.length} rows to ${outPath}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
